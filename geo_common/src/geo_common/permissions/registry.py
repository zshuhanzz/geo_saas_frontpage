def _route(
    service: Literal["saas", "agent"],
    methods: tuple[str, ...],
    path: str,
    capability: Capability,
    *,
    audit: bool = False,
    system_job: bool = False,
) -> RoutePolicy:
    return RoutePolicy(service, methods, path, capability, audit, system_job)



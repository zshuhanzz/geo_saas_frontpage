def get_feature(feature_key: str) -> FeatureDefinition:
    for feature in FEATURE_REGISTRY:
        if feature.key == feature_key:
            return feature
    raise KeyError(f"Unknown feature key: {feature_key}")


def capability_allowed(role: str, feature_key: str, capability: Capability) -> bool:
    return capability in ROLE_CAPABILITIES.get(role, {}).get(feature_key, ())


def resolve_frontend_feature(pathname: str) -> FeatureDefinition | None:
    normalized = pathname if pathname.startswith("/") else f"/{pathname}"
    for feature in FEATURE_REGISTRY:
        if any(fnmatchcase(normalized, pattern) for pattern in feature.frontend_routes):
            return feature
    return None


def resolve_backend_policies(
    service: Literal["saas", "agent"],
    method: str,
    path: str,
) -> tuple[tuple[FeatureDefinition, RoutePolicy], ...]:
    """Resolve the most-specific registered policies for an API request."""
    matches: list[tuple[int, FeatureDefinition, RoutePolicy]] = []
    normalized_method = method.upper()
    for feature in FEATURE_REGISTRY:
        for policy in feature.backend_routes:
            if policy.service != service or normalized_method not in policy.methods:
                continue
            if not fnmatchcase(path, policy.path):
                continue
            specificity = len(policy.path.replace("*", ""))
            matches.append((specificity, feature, policy))
    if not matches:
        return ()
    max_specificity = max(item[0] for item in matches)
    return tuple(
        (feature, policy)
        for specificity, feature, policy in matches
        if specificity == max_specificity
    )


def registry_payload() -> dict[str, object]:
    """Return the deterministic JSON-compatible frontend contract."""
    return {
        "version": 1,
        "capabilities": list(CAPABILITIES),
        "modules": [asdict(module) for module in MODULES],
        "features": [
            {
                **asdict(feature),
                "frontend_routes": list(feature.frontend_routes),
                "backend_routes": [
                    {
                        **asdict(route),
                        "methods": list(route.methods),
                    }
                    for route in feature.backend_routes
                ],
            }
            for feature in FEATURE_REGISTRY
        ],
        "role_capabilities": {
            role: {
                feature_key: list(capabilities)
                for feature_key, capabilities in feature_capabilities.items()
            }
            for role, feature_capabilities in ROLE_CAPABILITIES.items()
        },
    }
